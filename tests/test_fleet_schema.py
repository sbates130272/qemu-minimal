        # and a third of them are in none. This reads the declaration of
        # every setting: a path typed as an integer in the XSD would reject
        # what the RELAX NG schema accepts, and a boolean typed as a string
        # would drop a check, in a file no test document reaches.
        import xml.etree.ElementTree as ET
        rng_ns = "{http://relaxng.org/ns/structure/1.0}"
        xs = "{http://www.w3.org/2001/XMLSchema}"
