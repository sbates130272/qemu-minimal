    def test_an_attribute_default_from_a_doctype(self) -> None:
        # The parser (expat) applies a default an internal subset gives an
        # attribute; libxml2 does only when asked. The page says a
        # validator may differ from the parser here, in either direction.
        _require_lxml("parses with and without attribute defaults")
        rng = lxml_etree.RelaxNG(lxml_etree.parse(str(RNG)))
        xsd = lxml_etree.XMLSchema(lxml_etree.parse(str(XSD)))
        cases = (
            ("a default type on <server>",
             '<!DOCTYPE fleet [<!ATTLIST server type CDATA "ernic">]>'
             + devices("<server id='a'/>"), True),
            ("a default attribute on <fleet>",
             '<!DOCTYPE fleet [<!ATTLIST fleet version CDATA "1">]>'
             + fleet(), False))
        for index, (label, document, parser) in enumerate(cases):
            with self.subTest(case=label):
                path = self.dir / f"doctype-{index}.xml"
                path.write_text(document, encoding="utf-8")
                self.assertEqual(not FleetXml.problems(path), parser)
                plain = lxml_etree.parse(str(path))
                applied = lxml_etree.parse(
                    str(path), lxml_etree.XMLParser(attribute_defaults=True))
                for schema in (rng, xsd):
                    self.assertEqual(schema.validate(plain), not parser)
                    self.assertEqual(schema.validate(applied), parser)

    def test_an_entity_from_a_doctype(self) -> None:
        # An entity that holds text is the same document to every XML
        # parser. One that holds an element is not: the parser (expat) puts
        # the element in the fleet namespace and accepts, and libxml2 does
        # not, so the schemas refuse a document the parser accepts by way
        # of what the validator's XML parser did. The page says so.
        subset = '<!DOCTYPE fleet [<!ENTITY e "{}">]>'
        text = (subset.format("2")
                + fleet("<vm-count>&e;</vm-count>"))
        self.assertEqual(self._ask_all(9700, text), (True, True, True))
        element = (subset.format("<vm-count>2</vm-count>") + fleet("&e;"))
        path = self.dir / "entity.xml"
        path.write_text(element, encoding="utf-8")
        self.assertEqual(FleetXml.problems(path), [])
        self.assertEqual(
            FleetXml.parse(path).count, 2)
        page = " ".join(fleet_schema.render_markdown().split())
        self.assertIn("declares an entity that holds an element", page)
        self.assertIn(
            "leaves that element out of the fleet namespace", page)
        _require_lxml("reads the tree libxml2 built from an entity")
        tree = lxml_etree.parse(str(path))
        tags = [child.tag for child in tree.getroot()]
        rng = lxml_etree.RelaxNG(lxml_etree.parse(str(RNG)))
        xsd = lxml_etree.XMLSchema(lxml_etree.parse(str(XSD)))
        if tags == [f"{{{NS}}}vm-count"]:
            # A libxml2 that keeps the namespace: the grammar then has to
            # accept, and the sentence on the page is out of date.
            self.assertTrue(rng.validate(tree))
            self.assertTrue(xsd.validate(tree))
            self.fail("libxml2 now keeps the namespace of an element from "
                      "an entity; take the sentence off the page")
        self.assertEqual(tags, ["vm-count"])
        self.assertFalse(rng.validate(tree))
        self.assertFalse(xsd.validate(tree))

