"""The fleet XML schemas and reference page are what the parser's tables say.

qemu/schema/fleet.rng, qemu/schema/fleet.xsd and docs/fleet-xml.md are
generated by qemu_tool.fleet_schema from the tables in fleet_xml.py, and
committed. Three things can go wrong with that, and each has its tests here:

- the committed files are not what the generator writes now (Generated);
- a row of a table has no help text, so the page has a blank (Help);
- a schema says something the parser does not (Validation, Differential).

The last is the one that matters. The parser is the authority and the rule
for the RELAX NG schema is that it never rejects a document the parser
accepts. So every document below goes through the parser and both schemas:
FleetXml's own parse, and each schema run by libxml2 (lxml when it imports,
else `xmllint --relaxng` and `xmllint --schema`).
AGREE lists documents the parser and the RELAX NG schema must answer alike.
LOOSER lists the ones a grammar cannot refuse, where the schema accepts and
the parser does not, so that list is the measured form of "what the schema
cannot check".

The XSD is held to the RELAX NG schema the same way: it never rejects what
that accepts. XSD_TAKES and XSD_LOOSER are the documents the RELAX NG schema
refuses and the XSD accepts, each under the key of the looseness it shows
in fleet_schema.xsd_looser(), which is the list the XSD's header and the
page print. On every other document here the two schemas must agree.

With neither lxml nor xmllint the validating tests skip, and say so; under
CI=true they fail instead, as tests/test_ernic_identity.py does for its tools.

dump_documents() writes every document to a directory, for running other
validators (jing, an XSD converted by trang) over the same set by hand:

    python tests/test_fleet_schema.py --dump DIR
"""

