def documents() -> list[dict]:
    """Every document here, with the answer each validator has to give."""
    out = []
    for label, document, valid in AGREE:
        out.append({"label": label, "document": document, "parser": valid,
                    "rng": valid, "xsd": valid or label in XSD_TAKES})
    for label, document in LOOSER:
        out.append({"label": label, "document": document, "parser": False,
                    "rng": True, "xsd": True})
    for _key, label, document in XSD_LOOSER:
        out.append({"label": label, "document": document, "parser": False,
                    "rng": False, "xsd": True})
    return out


def dump_documents(directory: Path) -> None:
    """Write each document as NNNN.xml, and index.json with the answers."""
    directory.mkdir(parents=True, exist_ok=True)
    index = []
    for number, case in enumerate(documents()):
        name = f"{number:04d}.xml"
        (directory / name).write_text(case["document"], encoding="utf-8")
        index.append({"file": name, **{
            key: case[key] for key in ("label", "parser", "rng", "xsd")}})
    (directory / "index.json").write_text(
        json.dumps(index, indent=1) + "\n", encoding="utf-8")


