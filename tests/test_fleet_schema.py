class WhiteSpace(unittest.TestCase):
    """The schema strips what the parser strips.

    The parser uses str.strip() and int(), which take more than the four
    characters XML calls white space. A pattern written with those four
    would refuse a value the parser accepts.
    """

    def test_the_class_is_what_python_strips_of_what_xml_can_hold(self) -> None:
        def xml_char(cp: int) -> bool:
            return (cp in (0x9, 0xA, 0xD) or 0x20 <= cp <= 0xD7FF
                    or 0xE000 <= cp <= 0xFFFD or cp >= 0x10000)
        python = {cp for cp in range(sys.maxunicode + 1)
                  if xml_char(cp) and chr(cp).isspace()}
        schema = {cp for low, high in fleet_schema.SPACE_RANGES
                  for cp in range(low, high + 1)}
        self.assertEqual(schema, python)

    def test_only_ascii_letters_lower_to_the_boolean_words(self) -> None:
        # _convert lower()s a boolean, so a non-ASCII character that
        # lower-cases to one of these letters would be accepted by the
        # parser and not by a pattern of ASCII letters.
        letters = set("truefalsyno")
        odd = [hex(cp) for cp in range(0x80, sys.maxunicode + 1)
               if set(chr(cp).lower()) <= letters]
        self.assertEqual(odd, [])

    def test_a_digit_in_the_schema_is_every_digit_python_takes(self) -> None:
        # The schema does not use \d: that is the validator's Unicode table,
        # and libxml2's knows fewer than half the decimal digits int() takes.
        # A digit is [0-9] or any non-ASCII character that is not white
        # space, which holds for every decimal digit of any Unicode version.
        pattern = re.compile(fleet_schema._DIGIT)
        space = {cp for low, high in fleet_schema.SPACE_RANGES
                 for cp in range(low, high + 1)}
        digits = [chr(cp) for cp in range(sys.maxunicode + 1)
                  if unicodedata.decimal(chr(cp), None) is not None]
        self.assertGreater(len(digits), 600)
        for char in digits:
            self.assertEqual(int(char), unicodedata.decimal(char))
            self.assertNotIn(ord(char), space)
            self.assertTrue(pattern.fullmatch(char), f"U+{ord(char):04X}")
        self.assertNotIn("\\d", fleet_schema.render_rng())
        for char in "_+-. aZ":
            self.assertFalse(pattern.fullmatch(char), repr(char))


class Address(unittest.TestCase):
    """The address pattern is what ipaddress takes, no more and no less.

    The pattern is plain enough to be a Python regular expression too, so
    it is asked directly here, over far more strings than are worth a
    document each. Differential runs a sample of them through the validator.
    """

    PARTS = ("0", "1", "a", "F", "ff", "0001", "00001", "g", "12ab", "",
             "", "1.2.3.4", "255.0.0.255", "256.1.1.1", "01.2.3.4", "1.2.3")

    @classmethod
    def strings(cls, count: int, seed: int = 1) -> list[str]:
        rnd = random.Random(seed)
        out = []
        for _ in range(count):
            if rnd.random() < 0.3:
                text = "".join(rnd.choice("0129afF:.:[] g")
                               for _ in range(rnd.randint(0, 12)))
            else:
                text = ":".join(rnd.choice(cls.PARTS)
                                for _ in range(rnd.randint(0, 10)))
            if rnd.random() < 0.1:
                text = f"[{text}]"
            out.append(text)
        return out

    @staticmethod
    def parser_accepts(text: str) -> bool:
        setting = next(s for s in fleet_xml._SETTINGS
                       if s.tag == "publish-bind-addr")
        try:
            fleet_xml._convert(setting, text)
        except ValueError:
            return False
        return True

    def test_the_pattern_and_the_parser_agree(self) -> None:
        pattern = re.compile(fleet_schema.KIND_PATTERNS["addr"])
        accepted = 0
        for text in self.strings(60000):
            parser = self.parser_accepts(text)
            accepted += parser
            self.assertEqual(
                bool(pattern.fullmatch(text)), parser,
                f"{text!r}: the parser {'accepts' if parser else 'refuses'}")
        # Enough of each answer that agreeing means something.
        self.assertGreater(accepted, 1000)

    def test_the_pattern_counts_nothing(self) -> None:
        # libxml2 2.14.6 took a group of five hexadecimal digits when the
        # group was [0-9A-Fa-f]{1,4}; the pattern is written out instead.
        self.assertNotRegex(fleet_schema.KIND_PATTERNS["addr"], r"\{[0-9]")


