class OtherTables(unittest.TestCase):
    """The XSD the generator would write for tables it does not have yet.

    Two things the shipped tables do not reach, which a new server type or
    option could: two types with a child of one name, and a type with more
    once-only children than the any-order rule is written out for. Each has
    to give a schema that loads, takes what the parser takes, and says in
    the looser list what it gave up.
    """

    def setUp(self) -> None:
        _require_lxml("compiles a schema that is not a file")
        self._saved = {
            name: getattr(fleet_xml, name) for name in (
                "SERVER_TYPES", "SERVER_OPTIONS", "SERVER_OPTION_HELP",
                "_SERVER_SETTINGS", "_VALUE_FORMS")}
        self.addCleanup(lambda: [
            setattr(fleet_xml, name, value)
            for name, value in self._saved.items()])
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)

    def _add_type(self, kind: str, options: dict[str, str],
                  forms: dict[str, str] | None = None) -> None:
        fleet_xml.SERVER_TYPES = fleet_xml.SERVER_TYPES + (kind,)
        fleet_xml.SERVER_OPTIONS = {**fleet_xml.SERVER_OPTIONS, kind: options}
        fleet_xml.SERVER_OPTION_HELP = {
            **fleet_xml.SERVER_OPTION_HELP,
            kind: {name: (f"What {name} is for", "Any text")
                   for name in options}}
        fleet_xml._SERVER_SETTINGS = {**fleet_xml._SERVER_SETTINGS, kind: ()}
        fleet_xml._VALUE_FORMS = {
            **fleet_xml._VALUE_FORMS,
            **{(kind, name): form for name, form in (forms or {}).items()}}

    def _schemas(self):
        rng = lxml_etree.RelaxNG(lxml_etree.fromstring(
            fleet_schema.render_rng().encode()))
        xsd = lxml_etree.XMLSchema(lxml_etree.fromstring(
            fleet_schema.render_xsd().encode()))
        return rng, xsd

    def _ask(self, schemas, document: str) -> tuple[bool, bool, bool]:
        path = Path(self._tmp.name) / "case.xml"
        path.write_text(document, encoding="utf-8")
        parsed = lxml_etree.parse(str(path))
        return (not FleetXml.problems(path),
                schemas[0].validate(parsed), schemas[1].validate(parsed))

    def test_two_types_with_a_child_of_one_name(self) -> None:
        # <serial> once and held to a form in spdk; here repeatable, and
        # any text.
        self._add_type("disk", {"serial": "values", "model": "value"})
        keys = [key for key, _text in fleet_schema.xsd_looser()]
        self.assertIn("merged.spdk.or.disk", keys)
        schemas = self._schemas()
        for document, answers in (
                (server("disk", "<serial>a.b</serial><serial>c</serial>"
                        "<model>m</model>"), (True, True, True)),
                (server("spdk", "<serial>S1</serial>"
                        "<namespaces>kv:mem</namespaces>"),
                 (True, True, True)),
                # What the merge gives up: the other type's form and count.
                (server("spdk", "<serial>a.b</serial><serial>c</serial>"),
                 (False, False, True)),
                (server("spdk", "<model>m</model>"), (False, False, True)),
                (server("disk", "<model>m</model><model>n</model>"),
                 (False, False, False)),
                (server("disk", "<serial>a b\nc</serial>"),
                 (False, False, False))):
            with self.subTest(document=document):
                self.assertEqual(self._ask(schemas, document), answers)

    def test_a_type_with_too_many_once_only_children(self) -> None:
        count = fleet_schema._XSD_ONCE_MAX + 1
        names = [f"opt{n}" for n in range(count)]
        self._add_type("wide", {name: "value" for name in names})
        keys = [key for key, _text in fleet_schema.xsd_looser()]
        self.assertIn("repeat.wide", keys)
        schemas = self._schemas()
        every = "".join(f"<{name}>v</{name}>" for name in reversed(names))
        self.assertEqual(
            self._ask(schemas, server("wide", every)), (True, True, True))
        self.assertEqual(
            self._ask(schemas, server("wide", every + "<opt0>v</opt0>")),
            (False, False, True))
        self.assertEqual(
            self._ask(schemas, server(
                "wide", "<opt0>v</opt0><log-level>info</log-level>")),
            (False, False, False))

    def test_the_most_once_only_children_written_out(self) -> None:
        # At the limit the rule is still exact, and the schema still loads.
        count = fleet_schema._XSD_ONCE_MAX
        names = [f"opt{n}" for n in range(count)]
        self._add_type("wide", {**{name: "value" for name in names},
                                "more": "values"})
        self.assertNotIn(
            "repeat.wide", [key for key, _text in fleet_schema.xsd_looser()])
        schemas = self._schemas()
        every = "<more>x</more>".join(
            f"<{name}>v</{name}>" for name in reversed(names))
        self.assertEqual(
            self._ask(schemas, server("wide", every)), (True, True, True))
        self.assertEqual(
            self._ask(schemas, server("wide", every + "<opt2>v</opt2>")),
            (False, False, False))


class Command(unittest.TestCase):
    """`qemu-tool fleet-schema` prints what the generator returns."""

    def _run(self, *argv: str) -> str:
        args = cli._build_parser().parse_args(["fleet-schema", *argv])
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            args.func(args)
        return out.getvalue()

    def test_rng_is_the_default(self) -> None:
        self.assertEqual(self._run(), fleet_schema.render_rng())
        self.assertEqual(self._run("--format", "rng"), fleet_schema.render_rng())

    def test_md(self) -> None:
        self.assertEqual(
            self._run("--format", "md"), fleet_schema.render_markdown())

    def test_output_writes_the_file_and_prints_nothing(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "fleet.rng"
            self.assertEqual(self._run("--output", str(target)), "")
            self.assertEqual(
                target.read_text(encoding="utf-8"), fleet_schema.render_rng())

    def test_xsd(self) -> None:
        self.assertEqual(
            self._run("--format", "xsd"), fleet_schema.render_xsd())

    def test_output_dash_is_standard_output(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            before = os.getcwd()
            os.chdir(tmp)
            try:
                self.assertEqual(
                    self._run("--format", "xsd", "--output", "-"),
                    fleet_schema.render_xsd())
            finally:
                os.chdir(before)
            self.assertEqual(os.listdir(tmp), [])

    def test_an_empty_output_is_refused_in_words(self) -> None:
        # Path("") is ".", so `--output "$UNSET"` said "cannot write .: Is
        # a directory".
        for value, wanted in (
                ("", "--output needs a file name, and was given an empty "
                     "one"),
                (".", "--output . is a directory; name the file to write")):
            with self.subTest(output=value), \
                    tempfile.TemporaryDirectory() as tmp:
                before = os.getcwd()
                os.chdir(tmp)
                try:
                    with self.assertRaises(SystemExit) as caught:
                        self._run("--output", value)
                finally:
                    os.chdir(before)
                self.assertIn(wanted, str(caught.exception))
                self.assertTrue(str(caught.exception).startswith("Error: "))
                self.assertNotIn("cannot write .", str(caught.exception))
                self.assertEqual(os.listdir(tmp), [])

    def test_an_unknown_format_is_refused(self) -> None:
        with self.assertRaises(SystemExit), contextlib.redirect_stderr(
                io.StringIO()):
            cli._build_parser().parse_args(
                ["fleet-schema", "--format", "dtd"])

    def test_the_formats_are_the_generators(self) -> None:
        self.assertEqual(sorted(fleet_schema.FORMATS), ["md", "rng", "xsd"])
        action = next(
            a for a in cli._build_parser()._subparsers._group_actions[0]
            .choices["fleet-schema"]._actions if a.dest == "format")
        self.assertEqual(sorted(action.choices), sorted(fleet_schema.FORMATS))

    def _process(self, redirect: str) -> subprocess.CompletedProcess:
        # A real process: what is under test is the descriptor, which
        # redirect_stdout does not touch.
        code = (
            "import importlib.util, sys\n"
            f"pkg = {str(REPO_ROOT / 'qemu' / 'qemu-tool')!r}\n"
            "spec = importlib.util.spec_from_file_location('qemu_tool', "
            "pkg + '/__init__.py', submodule_search_locations=[pkg])\n"
            "module = importlib.util.module_from_spec(spec)\n"
            "sys.modules['qemu_tool'] = module\n"
            "spec.loader.exec_module(module)\n"
            "from qemu_tool import cli\n"
            "sys.argv = ['qemu-tool', 'fleet-schema']\n"
            "cli.main()\n")
        return subprocess.run(
            f'"{sys.executable}" -c "$CODE" {redirect}', shell=True,
            env={**os.environ, "CODE": code}, capture_output=True,
            text=True, check=False)

    def test_a_closed_standard_output_is_one_line_and_a_failure(self) -> None:
        proc = self._process(">&-")
        self.assertEqual(proc.returncode, 1, proc.stderr)
        self.assertEqual(
            proc.stderr,
            "Error: cannot write to standard output: it is closed\n")

    def test_a_full_disk_is_one_line_and_a_failure(self) -> None:
        if not Path("/dev/full").exists():
            self.skipTest("no /dev/full here")
        proc = self._process(">/dev/full")
        self.assertEqual(proc.returncode, 1, proc.stderr)
        self.assertEqual(len(proc.stderr.splitlines()), 1, proc.stderr)
        self.assertTrue(proc.stderr.startswith(
            "Error: cannot write to standard output: "), proc.stderr)

    def test_standard_output_is_the_schema(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "out"
            proc = self._process(f'> "{target}"')
            self.assertEqual((proc.returncode, proc.stderr), (0, ""))
            self.assertEqual(
                target.read_text(encoding="utf-8"), fleet_schema.render_rng())


