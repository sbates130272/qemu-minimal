    def test_an_integer_of_many_underscores(self) -> None:
        # int() takes single underscores between digits, as many as there
        # are digits, and libxml2 takes them with either schema. A
        # validator on java.util.regex (jing) overflows its stack on this
        # one, because the underscore group is a repeated group and no
        # pattern without one is exact. The page has to go on saying so
        # for as long as the pattern has that group.
        self.assertEqual(
            self._ask_all(
                9510, fleet(f"<vm-count>{'1_' * 2000}1</vm-count>")),
            (True, True, True))
        for refused in ("1__2", "1_", "_1"):
            with self.subTest(integer=refused):
                self.assertEqual(
                    self._ask_all(
                        9511, fleet(f"<vm-count>{refused}</vm-count>")),
                    (False, False, False))
        self.assertIn(
            f"(_{fleet_schema._DIGIT}+)*", fleet_schema.KIND_PATTERNS["int"])
        page = " ".join(fleet_schema.render_markdown().split())
        self.assertIn("thousands of single underscores", page)
        self.assertIn("`StackOverflowError`", page)
        self.assertIn(
            "thousands of underscores can stop a Java validator", page)

