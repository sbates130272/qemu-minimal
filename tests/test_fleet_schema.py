    def test_children_in_every_order_and_none_twice(self) -> None:
        # The XSD writes "any order, some at most once" out as a group for
        # every set of children seen so far. Every order of each type's
        # once-only children, with a repeatable one between each pair, has
        # to pass all three; the same with any one of them again has to
        # fail all three.
        samples = {"backend": "<backend type='s3'>bucket=x</backend>",
                   "config": "<config>a.json</config>",
                   "serial": "<serial>S1</serial>",
                   "cpumask": "<cpumask>0x4</cpumask>",
                   "namespaces": "<namespaces>kv:mem</namespaces>",
                   "verbose": "<verbose/>"}
        index = 0
        for kind in fleet_xml.SERVER_TYPES:
            children = fleet_schema._server_children(kind)
            element = {name: samples.get(name, f"<{name}>v</{name}>")
                       for name, _shape in children}
            once = [name for name, shape in children
                    if shape not in ("values", "flags")]
            repeat = [element[name] for name, shape in children
                      if shape in ("values", "flags")]
            between = "".join(repeat)
            for order in itertools.permutations(once):
                inner = between + "".join(
                    element[name] + between for name in order)
                index += 1
                self.assertEqual(
                    self._ask_all(index, server(kind, inner)),
                    (True, True, True), f"{kind}: {inner}")
                for again in order:
                    index += 1
                    self.assertEqual(
                        self._ask_all(
                            index, server(kind, inner + element[again])),
                        (False, False, False),
                        f"{kind}: {inner} and {again} again")
        self.assertGreater(index, 150)

