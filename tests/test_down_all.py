"""Tests for `qemu-tool down-all`.

This command removes containers, so the tests are mostly about the two ways
it could remove the WRONG ones:

* Identifying a stack by something another project could coincidentally
  match. `qemu-1` is a service name anyone might use; the compose file's
  provenance header is not.
* Claiming a stack is yours when it is not. A stack started before the
  containers ran as the caller is root's, and a non-root caller cannot stop
  it -- saying otherwise would produce a confident failure.

Plus the obvious one: the confirmation must not default to yes.

No Docker here -- `docker inspect` output is synthesised, so the tests say
what the code does with a given answer rather than what this host happens to
be running.

Stdlib unittest, like the rest of tests/. Run with:

    python3 -m unittest discover -s tests -v
"""

from __future__ import annotations

import importlib.util
import io
import os
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path
from unittest import mock

REPO_ROOT = Path(__file__).resolve().parent.parent

_HEADER = (
    "---\n"
    "# Generated by `qemu-tool gen-compose`. Do not edit.\n"
    "# env-file: /tmp/env\n"
    "# env-sha256: " + "0" * 64 + "\n"
)


def _load_package():
    pkg = REPO_ROOT / "qemu" / "qemu-tool"
    spec = importlib.util.spec_from_file_location(
        "qemu_tool", pkg / "__init__.py", submodule_search_locations=[str(pkg)]
    )
    module = importlib.util.module_from_spec(spec)
    sys.modules["qemu_tool"] = module
    spec.loader.exec_module(module)
    return module


_load_package()
from qemu_tool import down_all  # noqa: E402


def _container(project: str, name: str, config_file: str, user: str,
               working_dir: str = "/wd", env_files: str = "") -> dict:
    """One `docker inspect` record, shaped as compose really labels them."""
    return {
        "Name": f"/{name}",
        "Config": {
            "User": user,
            "Labels": {
                "com.docker.compose.project": project,
                "com.docker.compose.project.config_files": config_file,
                "com.docker.compose.project.working_dir": working_dir,
                "com.docker.compose.project.environment_file": env_files,
            },
        },
    }


def _discover(records):
    with mock.patch.object(down_all, "_inspect_running", lambda: records):
        return down_all.discover()


class Identification(unittest.TestCase):
    """What counts as a qemu-tool stack. Never a service name."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.generated = Path(self.tmp.name) / "docker-compose.yml"
        self.generated.write_text(_HEADER)

    def test_a_generated_stack_is_found_by_its_provenance_header(self):
        found = _discover([_container("fleet", "fleet-qemu-1-1",
                                      str(self.generated), "1000:1000")])
        self.assertEqual([s.project for s in found], ["fleet"])

    def test_a_committed_stack_is_found_by_its_directory_name(self):
        """The hand-written stacks have no header -- they are not generated
        -- so they are recognised by the directory this repo ships them in.
        """
        d = Path(self.tmp.name) / "vfio-user-ernic-2vm"
        d.mkdir()
        cfg = d / "docker-compose.yml"
        cfg.write_text("services: {}\n")
        found = _discover([_container("x", "x-qemu-1", str(cfg), "1000:1000")])
        self.assertEqual([s.project for s in found], ["x"])

    def test_an_unrelated_project_is_ignored(self):
        """The whole safety property. Someone else's compose project with a
        service called qemu-1 must not be torn down by this.
        """
        other = Path(self.tmp.name) / "someone-elses.yml"
        other.write_text("services:\n  qemu-1:\n    image: alpine\n")
        self.assertEqual(
            _discover([_container("theirs", "theirs-qemu-1-1", str(other),
                                  "1000:1000")]),
            [])

    def test_a_container_outside_compose_is_ignored(self):
        rec = {"Name": "/loose", "Config": {"User": "", "Labels": {}}}
        self.assertEqual(_discover([rec]), [])

    def test_a_vanished_compose_file_is_ignored(self):
        """Not an error: it cannot be identified, so it is not claimed."""
        self.assertEqual(
            _discover([_container("gone", "gone-1", "/no/such/file.yml",
                                  "1000:1000")]),
            [])


class Ownership(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.cfg = Path(self.tmp.name) / "docker-compose.yml"
        self.cfg.write_text(_HEADER)

    def _stack(self, *users):
        return _discover([
            _container("fleet", f"fleet-{i}", str(self.cfg), u)
            for i, u in enumerate(users)
        ])[0]

    def test_any_container_as_my_uid_makes_it_mine(self):
        """Any, not all: a stack legitimately mixes uids -- the stats
        exporters are pinned to 65534 and tapsetup stays root -- so requiring
        all of them would find nothing.
        """
        stack = self._stack("1000:1000", "65534:65534", "")
        self.assertTrue(stack.owned_by(1000))

    def test_a_root_era_stack_is_not_mine(self):
        """Every container root, which is what a stack started before the
        CONTAINER_USER work looks like. Correct, and the reason the command
        lists what it skipped.
        """
        stack = self._stack("", "")
        self.assertFalse(stack.owned_by(1000))

    def test_another_users_stack_is_not_mine(self):
        self.assertFalse(self._stack("4242:4242").owned_by(1000))

    def test_the_gid_does_not_have_to_match(self):
        """A stack started with a different primary group is still yours;
        the uid is what decides whether you can stop it."""
        self.assertTrue(self._stack("1000:999").owned_by(1000))


class TeardownCommand(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.d = Path(self.tmp.name)
        self.cfg = self.d / "docker-compose.yml"
        self.cfg.write_text(_HEADER)
        self.env = self.d / "settings"
        self.env.write_text("VM_COUNT=1\n")

    def _cmd(self, env_files=""):
        stack = _discover([
            _container("fleet", "fleet-qemu-1-1", str(self.cfg), "1000:1000",
                       working_dir=str(self.d), env_files=env_files)
        ])[0]
        return down_all._teardown_cmd(stack)

    def test_the_project_is_pinned_explicitly(self):
        """Compose otherwise derives it from the working directory, and a
        teardown run against the wrong one resolves to an empty project and
        reports success -- the leading theory for the containers that
        survived a `down` by 41 hours.
        """
        cmd = self._cmd()
        self.assertEqual(cmd[:4], ["docker", "compose", "-p", "fleet"])

    def test_every_profile_is_enabled(self):
        self.assertIn("--profile", self._cmd())
        self.assertIn("*", self._cmd())

    def test_it_is_a_down_with_remove_orphans(self):
        cmd = self._cmd()
        self.assertEqual(cmd[-2:], ["down", "--remove-orphans"])

    def test_recorded_env_files_are_passed_through(self):
        cmd = self._cmd(env_files=str(self.env))
        self.assertIn("--env-file", cmd)
        self.assertIn(str(self.env), cmd)

    def test_a_vanished_env_file_is_dropped_rather_than_passed(self):
        """Compose refuses outright on a missing --env-file, and a stack
        whose settings were tidied away is exactly the kind this command
        exists to clean up."""
        cmd = self._cmd(env_files=f"{self.env},/gone/settings")
        self.assertIn(str(self.env), cmd)
        self.assertNotIn("/gone/settings", cmd)


class Confirmation(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        cfg = Path(self.tmp.name) / "docker-compose.yml"
        cfg.write_text(_HEADER)
        self.records = [_container("fleet", "fleet-qemu-1-1", str(cfg),
                                   f"{os.getuid()}:{os.getgid()}")]

    def _run(self, reply, **kw):
        out = io.StringIO()
        with mock.patch.object(down_all, "_inspect_running",
                               lambda: self.records), \
             mock.patch.object(down_all.subprocess, "run") as sub, \
             mock.patch("builtins.input", side_effect=[reply]), \
             redirect_stdout(out):
            # A bare Mock's .returncode is a Mock, which is truthy and so
            # reads as a failed teardown -- say 0 explicitly.
            sub.return_value = mock.Mock(returncode=0)
            down_all.run(**kw)
        return out.getvalue(), sub

    def test_a_bare_enter_does_not_remove_anything(self):
        """It removes containers; Enter must not be the thing that does it."""
        out, sub = self._run("")
        self.assertIn("Nothing was stopped", out)
        sub.assert_not_called()

    def test_n_declines(self):
        out, sub = self._run("n")
        self.assertIn("Nothing was stopped", out)
        sub.assert_not_called()

    def test_y_proceeds(self):
        _, sub = self._run("y")
        sub.assert_called()

    def test_eof_declines(self):
        """No terminal is not consent."""
        out = io.StringIO()
        with mock.patch.object(down_all, "_inspect_running",
                               lambda: self.records), \
             mock.patch.object(down_all.subprocess, "run") as sub, \
             mock.patch("builtins.input", side_effect=EOFError), \
             redirect_stdout(out):
            down_all.run()
        self.assertIn("Nothing was stopped", out.getvalue())
        sub.assert_not_called()

    def test_dry_run_never_prompts_and_never_removes(self):
        out = io.StringIO()
        with mock.patch.object(down_all, "_inspect_running",
                               lambda: self.records), \
             mock.patch.object(down_all.subprocess, "run") as sub, \
             mock.patch("builtins.input", side_effect=AssertionError("prompted")), \
             redirect_stdout(out):
            down_all.run(dry_run=True)
        self.assertIn("--dry-run", out.getvalue())
        sub.assert_not_called()


class Scope(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        cfg = Path(self.tmp.name) / "docker-compose.yml"
        cfg.write_text(_HEADER)
        self.cfg = cfg

    def _run_dry(self, records, **kw):
        out = io.StringIO()
        with mock.patch.object(down_all, "_inspect_running", lambda: records), \
             redirect_stdout(out):
            down_all.run(dry_run=True, **kw)
        return out.getvalue()

    def test_someone_elses_stack_is_listed_as_skipped_with_the_reason(self):
        """Silently ignoring it would read as "there is nothing else here",
        and the usual cause -- a root-era stack -- is not obvious."""
        records = [_container("theirs", "theirs-1", str(self.cfg), "")]
        out = self._run_dry(records)
        self.assertIn("do not own", out)
        self.assertIn("theirs", out)
        self.assertIn("sudo", out)

    def test_all_users_without_root_is_refused(self):
        """Their containers cannot be stopped without it, so the flag would
        promise something it cannot deliver."""
        records = [_container("theirs", "theirs-1", str(self.cfg), "")]
        with mock.patch.object(down_all.os, "getuid", lambda: 1000), \
             self.assertRaises(SystemExit) as ctx:
            self._run_dry(records, all_users=True)
        self.assertIn("needs root", str(ctx.exception))

    def test_root_takes_every_stack(self):
        """`sudo qemu-tool down-all` is the system-wide form, which is how
        it reads."""
        records = [_container("a", "a-1", str(self.cfg), "4242:4242"),
                   _container("b", "b-1", str(self.cfg), "")]
        with mock.patch.object(down_all.os, "getuid", lambda: 0):
            out = self._run_dry(records)
        self.assertIn("Will tear down 2 stack(s)", out)
        self.assertNotIn("do not own", out)

    def test_nothing_running_says_so(self):
        out = io.StringIO()
        with mock.patch.object(down_all, "_inspect_running", lambda: []), \
             redirect_stdout(out):
            down_all.run()
        self.assertIn("No running qemu-tool stacks", out.getvalue())


if __name__ == "__main__":
    unittest.main()
