"""One kernel in the golden image, and grub told which by name.

The baked image used to carry the Ubuntu release kernel beside the pinned
mainline one: some 370 MB nothing boots, and the entry grub would turn to
next -- a kernel no module in the image was built for. The golden bake now
purges every kernel but the running one, and rocm_ernic_setup names the
pinned kernel to grub rather than leaving it to sort first.

A wrong step here is an image that does not boot, published. No bake runs in
this suite, so what is pinned is each piece that decides: where the tasks
sit, what the two scripts the purge runs say about a given system, and what
the acceptance check makes of a grub.cfg. The grub.cfg fixtures are written
out the way Ubuntu resolute's /etc/grub.d/00_header and 10_linux write one
(grub2-common 2.14-2ubuntu2.1), not generated by grub-mkconfig.

    python3 -m unittest discover -s tests -v
"""

