def _entry(version, kind, indent, boot, partuuid):
    ident = (f"gnulinux-simple-{UUID}" if kind == "simple"
             else f"gnulinux-{version}-{kind}-{UUID}")
    title = {"simple": "Ubuntu",
             "advanced": f"Ubuntu, with Linux {version}",
             "recovery": f"Ubuntu, with Linux {version} (recovery mode)"}[kind]
    args = ("recovery nomodeset dis_ucode_ldr" if kind == "recovery"
            else "console=tty1 console=ttyS0")
    lines = [
        f"menuentry '{title}' --class ubuntu --class gnu-linux --class gnu "
        f"--class os $menuentry_id_option '{ident}' {{",
        "\trecordfail", "\tload_video", "\tgfxmode $linux_gfx_mode",
        "\tinsmod gzio",
        "\tif [ x$grub_platform = xxen ]; then insmod xzio; insmod lzopio; fi",
        "\tinsmod part_gpt", "\tinsmod ext2",
        f"\tsearch --no-floppy --fs-uuid --set=root {UUID}"]
    kernel = f"{boot}/vmlinuz-{version}"
    initrd = f"{boot}/initrd.img-{version}"
    if partuuid:
        lines += [
            '\tif [ "${initrdfail}" = 1 ]; then',
            "\t\techo\t'GRUB_FORCE_PARTUUID set, initrdless boot failed. "
            "Attempting with initrd.'",
            f"\t\tlinux\t{kernel} root=PARTUUID=0a1b2c3d-01 ro {args}",
            f"\t\tinitrd\t{initrd}",
            "\telse",
            "\t\techo\t'GRUB_FORCE_PARTUUID set, attempting initrdless boot.'",
            f"\t\tlinux\t{kernel} root=PARTUUID=0a1b2c3d-01 ro {args} panic=-1",
            "\tfi", "\tinitrdfail"]
    else:
        lines += [f"\tlinux\t{kernel} root=UUID={UUID} ro {args}",
                  f"\tinitrd\t{initrd}"]
    lines.append("}")
    return [indent + line for line in lines]


def grub_cfg(kernels, default="0", boot="/boot", partuuid=False,
             submenu=True):
    """A grub.cfg for *kernels*, the first of them the top-level entry."""
    out = [
        "#", "# DO NOT EDIT THIS FILE", "#",
        "### BEGIN /etc/grub.d/00_header ###",
        "if [ -s $prefix/grubenv ]; then", "  set have_grubenv=true",
        "  load_env", "fi",
        'if [ "${initrdfail}" = 2 ]; then', "   set initrdfail=",
        'elif [ "${initrdfail}" = 1 ]; then',
        '   set next_entry="${prev_entry}"', "   set prev_entry=",
        "   save_env prev_entry", '   if [ "${next_entry}" ]; then',
        "      set initrdfail=2", "   fi", "fi",
        'if [ "${next_entry}" ] ; then', '   set default="${next_entry}"',
        "   set next_entry=", "   save_env next_entry",
        "   set boot_once=true", "else", f'   set default="{default}"', "fi",
        "", 'if [ x"${feature_menuentry_id}" = xy ]; then',
        '  menuentry_id_option="--id"', "else", '  menuentry_id_option=""',
        "fi", "", "export menuentry_id_option", "",
        "function savedefault {", '  if [ -z "${boot_once}" ]; then',
        '    saved_entry="${chosen}"', "    save_env saved_entry", "  fi", "}",
        "function initrdfail {", '    if [ -n "${have_grubenv}" ]; then '
        'if [ -n "${partuuid}" ]; then', "      set initrdfail=1",
        "      save_env initrdfail", "    fi; fi", "}",
        "function recordfail {", "  set recordfail=1", "}",
        "### END /etc/grub.d/00_header ###", "",
        "### BEGIN /etc/grub.d/10_linux ###"]
    if not submenu:
        for version in kernels:
            out += _entry(version, "advanced", "", boot, partuuid)
            out += _entry(version, "recovery", "", boot, partuuid)
    else:
        out += _entry(kernels[0], "simple", "", boot, partuuid)
        out.append("submenu 'Advanced options for Ubuntu' "
                   f"$menuentry_id_option 'gnulinux-advanced-{UUID}' {{")
        for version in kernels:
            out += _entry(version, "advanced", "\t", boot, partuuid)
            out += _entry(version, "recovery", "\t", boot, partuuid)
        out.append("}")
    out += ["", "### END /etc/grub.d/10_linux ###", "",
            "### BEGIN /etc/grub.d/40_custom ###",
            "### END /etc/grub.d/40_custom ###", ""]
    return "\n".join(out)


class GrubCheck(unittest.TestCase):
    """The resolver in qemu/checks/rocm-golden.sh, lifted out and run."""

    @classmethod
    def setUpClass(cls):
        text = CHECK.read_text()
        cls.program = text[text.index("<<'GRUBPY'\n") + len("<<'GRUBPY'\n"):
                           text.index("\nGRUBPY\n")]

    def _resolve(self, cfg, env="", running=RUNNING):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            (tmp / "grub.cfg").write_text(cfg)
            (tmp / "grubenv").write_text(env)
            done = subprocess.run(
                [sys.executable, "-", str(tmp / "grub.cfg"),
                 str(tmp / "grubenv"), running],
                input=self.program, capture_output=True, text=True)
        return done.returncode, done.stdout + done.stderr

    def assertBoots(self, cfg, env="", title=None):
        rc, out = self._resolve(cfg, env)
        self.assertEqual(rc, 0, out)
        self.assertIn(f"loads vmlinuz-{RUNNING}", out)
        if title:
            self.assertIn(repr(title), out)

    def assertRefused(self, cfg, why, env=""):
        rc, out = self._resolve(cfg, env)
        self.assertNotEqual(rc, 0, out)
        self.assertIn("ERROR: grub:", out)
        self.assertIn(why, out)

    def test_the_baked_image_one_kernel_default_zero(self):
        self.assertBoots(grub_cfg([RUNNING]), title="Ubuntu")

    def test_the_pin_puts_the_pinned_kernel_first_over_a_newer_one(self):
        """GRUB_TOP_LEVEL: 7.2.6 leads although 7.3 sorts above it."""
        self.assertBoots(grub_cfg([RUNNING, "7.3.0-5-generic"]))

    def test_an_image_whose_first_entry_is_another_kernel_is_refused(self):
        """No pin, and a newer kernel: what version sort alone would boot."""
        self.assertRefused(grub_cfg(["7.3.0-5-generic", RUNNING]),
                           "but the guest is running")
        self.assertRefused(grub_cfg([OLD]), "but the guest is running")

    def test_every_form_of_default_grub_accepts(self):
        advanced = f"gnulinux-advanced-{UUID}"
        entry = f"gnulinux-{RUNNING}-advanced-{UUID}"
        both = [OLD, RUNNING]
        for spec in (f"{advanced}>{entry}", "1>2",
                     f"Advanced options for Ubuntu>Ubuntu, with Linux {RUNNING}",
                     f"1>{entry}"):
            with self.subTest(spec=spec):
                self.assertBoots(grub_cfg(both, default=spec),
                                 title=f"Ubuntu, with Linux {RUNNING}")
        self.assertRefused(grub_cfg(both, default="0"),
                           "but the guest is running")
        self.assertRefused(grub_cfg(both, default="1>0"),
                           "but the guest is running")

    def test_a_default_that_names_nothing_is_refused_not_fallen_back_on(self):
        for spec in ("7", "1>9", "gnulinux-9.9.9-advanced-x", "nonsense"):
            self.assertRefused(grub_cfg([RUNNING], default=spec),
                               "names no entry")

    def test_a_default_that_stops_at_the_submenu_is_refused(self):
        self.assertRefused(grub_cfg([RUNNING], default="1"), "is the submenu")
        self.assertRefused(grub_cfg([RUNNING], default="0>0"), "goes below")

    def test_saved_is_read_from_the_environment_block(self):
        cfg = grub_cfg([OLD, RUNNING], default="${saved_entry}")
        entry = f"gnulinux-advanced-{UUID}>gnulinux-{RUNNING}-advanced-{UUID}"
        self.assertBoots(cfg, env=f"# GRUB Environment Block\n"
                                  f"saved_entry={entry}\n###\n")
        # Unset, grub boots entry 0, which here is the other kernel.
        self.assertRefused(cfg, "but the guest is running",
                           env="# GRUB Environment Block\n")
        self.assertBoots(grub_cfg([RUNNING], default="${saved_entry}"))

    def test_a_one_shot_next_entry_is_refused(self):
        self.assertRefused(grub_cfg([RUNNING]), "next_entry is set",
                           env="next_entry=1>2\n")
        # Present and empty is how grub leaves it once it has been used.
        self.assertBoots(grub_cfg([RUNNING]), env="next_entry=\n")

    def test_a_separate_boot_partition_and_the_initrdless_form(self):
        self.assertBoots(grub_cfg([RUNNING], boot=""))
        self.assertBoots(grub_cfg([RUNNING], partuuid=True))
        self.assertBoots(grub_cfg([RUNNING], boot="", partuuid=True))
        self.assertRefused(grub_cfg([OLD], partuuid=True),
                           "but the guest is running")

    def test_a_menu_without_submenus(self):
        self.assertBoots(grub_cfg([RUNNING, OLD], submenu=False))
        self.assertRefused(grub_cfg([OLD, RUNNING], submenu=False),
                           "but the guest is running")
        self.assertBoots(grub_cfg([OLD, RUNNING], submenu=False, default="2"))

    def test_a_kernel_whose_name_only_begins_the_same_is_not_it(self):
        self.assertRefused(grub_cfg([RUNNING + ".old"]),
                           "but the guest is running")

    def test_a_configuration_it_cannot_read_is_refused(self):
        self.assertRefused("", "expected one configured default")
        self.assertRefused('set default="0"\nmenuentry \'x\' {\n',
                           "unbalanced braces")
        self.assertRefused('set default="0"\n}\n', "unbalanced braces")
        self.assertRefused(
            'set default="0"\nmenuentry \'x\' --id \'x\' {\n\techo hi\n}\n',
            "loads no kernel")
        two = grub_cfg([RUNNING]).replace(
            "### END /etc/grub.d/00_header ###",
            'set default="3"\n### END /etc/grub.d/00_header ###')
        self.assertRefused(two, "expected one configured default")


class GuestCheck(unittest.TestCase):
    """What qemu/checks/rocm-golden.sh asserts on the booted guest."""

    def setUp(self):
        text = CHECK.read_text()
        self.section = text[text.index(
            "# One kernel, and it is the one grub boots"):]

    def test_one_installed_kernel_image_and_it_is_the_running_one(self):
        self.assertIn("'linux-image-*' |\n    awk '$1 == \"ii\" { print $2 }'",
                      self.section)
        self.assertIn('grep -c .)" != 1', self.section)
        self.assertIn('*"${_kver}") ;;', self.section)

    def test_no_metapackage_that_would_bring_a_kernel_back(self):
        defaults = yaml.safe_load((SLIM / "defaults/main.yml").read_text())
        for name in defaults["image_slim_kernel_metapackages"]:
            self.assertIn(name, self.section)

    def test_nothing_of_another_kernel_remains(self):
        for line in ('if [ "$(ls /lib/modules)" != "${_kver}" ]; then',
                     'if [ "$(ls /boot/vmlinuz-*)" != '
                     '"/boot/vmlinuz-${_kver}" ]; then',
                     'test -s "/boot/initrd.img-${_kver}"',
                     "find /var/lib/dkms -mindepth 3 -maxdepth 3 -type d "
                     "-name '[0-9]*' \\\n    ! -name \"${_kver}\")",
                     "dkms status | awk -F', ' -v k=\"${_kver}\" "
                     "'NF >= 3 && $2 != k'"):
            self.assertIn(line, self.section)

    @unittest.skipUnless(shutil.which("awk"), "needs awk")
    def test_the_dkms_filter_reads_dkms_three_status_lines(self):
        program = re.search(r"awk -F', ' -v k=\"\$\{_kver\}\" '([^']+)'",
                            self.section).group(1)
        status = (f"amdgpu/7.1.9-2278356.26.04, {RUNNING}, x86_64: installed\n"
                  f"ionic-ernic/7.2.6, {RUNNING}, x86_64: installed\n"
                  "sdxi/1.0: added\n")
        other = f"amdgpu/7.1.9-2278356.26.04, {OLD}, x86_64: installed\n"

        def run(text):
            return subprocess.run(
                ["awk", "-F", ", ", "-v", f"k={RUNNING}", program],
                input=text, capture_output=True, text=True, check=True).stdout
        self.assertEqual(run(status), "")
        self.assertEqual(run(status + other), other)

    def test_grub_is_read_as_root_and_an_unreadable_one_fails(self):
        self.assertIn('sudo -n cat /boot/grub/grub.cfg | tee "${_grubcfg}"',
                      self.section)
        self.assertIn('test -s "${_grubcfg}"', self.section)
        self.assertIn('python3 - "${_grubcfg}" "${_grubenv}" "${_kver}" '
                      "<<'GRUBPY'", self.section)

    def test_both_lanes_run_the_check_against_the_booted_guest(self):
        for name in ("qemu-minimal-publish-qcow-rocm-golden.yml",
                     "qemu-minimal-ansible-playbook-test-vm-rocm-golden.yml"):
            text = (REPO / ".github/workflows" / name).read_text()
            self.assertIn("cat qemu/checks/rocm-golden.sh; } |", text, name)


