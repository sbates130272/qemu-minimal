def _flatten(tasks):
    for task in tasks:
        yield task
        for section in ("block", "rescue", "always"):
            yield from _flatten(task.get(section, []))


def _tasks(path):
    return list(_flatten(yaml.safe_load(path.read_text())))


def _named(tasks, name):
    return next(t for t in tasks if t.get("name") == name)


class Playbook(unittest.TestCase):

    def setUp(self):
        self.plays = yaml.safe_load(GOLDEN.read_text())
        self.slim = next(p for p in self.plays
                         if p.get("name") == "Slim the baked image")

    def test_only_the_golden_slim_play_purges_kernels(self):
        self.assertIs(self.slim["vars"]["image_slim_purge_old_kernels"], True)
        defaults = yaml.safe_load((SLIM / "defaults/main.yml").read_text())
        self.assertIs(defaults["image_slim_purge_old_kernels"], False)
        for path in PLAYBOOKS.glob("*.yml"):
            if path != GOLDEN:
                self.assertNotIn("image_slim_purge_old_kernels",
                                 path.read_text(), path.name)
        self.assertEqual(
            GOLDEN.read_text().count("image_slim_purge_old_kernels"), 1)

    def test_the_slim_play_is_the_last_bake_play(self):
        """Nothing that boots or builds may follow the purge in a bake."""
        bake = [p["name"] for p in self.plays
                if p.get("tags") == ["install"] and "name" in p]
        self.assertEqual(bake[-1], "Slim the baked image")

    def test_the_purge_is_refused_unless_the_pinned_kernel_is_running(self):
        """The role keeps the RUNNING kernel, whichever that is."""
        guard = self.slim["pre_tasks"][0]
        self.assertEqual(
            guard["ansible.builtin.assert"]["that"],
            ["ansible_kernel.split('-')[0] == ionic_kernel_pin "
             "| regex_replace('^v', '')"])
        self.assertIs(self.slim["gather_facts"], True)
        # The pin through its anchor, not a second copy of the version.
        text = GOLDEN.read_text()
        play = text[text.index("- name: Slim the baked image"):]
        self.assertIn("ionic_kernel_pin: *ionic_kernel_pin",
                      play[:play.index("roles:")])


class GrubPin(unittest.TestCase):
    """rocm_ernic_setup's kernel.yml: installed, named to grub, then booted."""

    def setUp(self):
        self.top = yaml.safe_load((ERNIC / "tasks/kernel.yml").read_text())
        self.names = [t["name"] for t in self.top]
        self.defaults = yaml.safe_load(
            (ERNIC / "defaults/main.yml").read_text())

    def test_the_order_is_install_pin_regenerate_boot_assert(self):
        order = [self.names.index(n) for n in (
            "Install the pinned mainline kernel",
            "Pin the boot entry to the pinned kernel",
            "Regenerate the grub configuration",
            "Boot the pinned kernel",
            "Assert the guest booted the pinned kernel")]
        self.assertEqual(order, sorted(order))

    def test_a_guest_already_on_the_pinned_kernel_is_pinned_too(self):
        pin = _named(self.top, "Pin the boot entry to the pinned kernel")
        self.assertEqual(pin["when"], "rocm_ernic_setup_kernel_grub_pin | bool")
        self.assertIs(self.defaults["rocm_ernic_setup_kernel_grub_pin"], True)
        for name in ("Install the pinned mainline kernel",
                     "Boot the pinned kernel"):
            self.assertEqual(
                _named(self.top, name)["when"],
                "not (rocm_ernic_setup_kernel_current | bool)")

    def test_the_reboot_follows_the_pin_so_it_is_the_pins_first_test(self):
        boot = _named(self.top, "Boot the pinned kernel")["block"]
        self.assertIn("ansible.builtin.reboot",
                      _named(boot, "Reboot into the new kernel"))
        install = _named(self.top, "Install the pinned mainline kernel")
        self.assertFalse(any("ansible.builtin.reboot" in t
                             for t in _flatten(install["block"])))

    def test_the_kernel_is_named_by_path_and_must_be_the_only_match(self):
        pin = _named(self.top, "Pin the boot entry to the pinned kernel")
        find = pin["block"][0]["ansible.builtin.find"]
        self.assertEqual(find["paths"], "/boot")
        self.assertEqual(find["patterns"],
                         "vmlinuz-{{ rocm_ernic_setup_kver }}-*")
        check = pin["block"][1]["ansible.builtin.assert"]
        self.assertEqual(
            check["that"], "rocm_ernic_setup_kernel_images.files | length == 1")

    def test_the_drop_in_is_what_grub_and_the_check_both_read(self):
        pin = _named(self.top, "Pin the boot entry to the pinned kernel")
        write = _named(pin["block"],
                       "Write the grub drop-in that names the pinned kernel")
        copy = write["ansible.builtin.copy"]
        self.assertEqual(copy["dest"],
                         "{{ rocm_ernic_setup_kernel_grub_dropin }}")
        path = self.defaults["rocm_ernic_setup_kernel_grub_dropin"]
        # Under grub.d, where the cloud image's own settings are; and named
        # to be read after them.
        self.assertRegex(path, r"^/etc/default/grub\.d/99-[a-z-]+\.cfg$")
        lines = [line for line in copy["content"].splitlines()
                 if not line.startswith("#")]
        self.assertEqual(lines, [
            'GRUB_TOP_LEVEL="{{ rocm_ernic_setup_kernel_images.files[0].path }}"',
            "GRUB_DEFAULT=0"])
        # The acceptance check reads the same file for the same two lines.
        check = CHECK.read_text()
        self.assertIn(
            'grep -qx "GRUB_TOP_LEVEL=\\"/boot/vmlinuz-${_kver}\\"" \\\n'
            f"    {path}\n", check)
        self.assertIn(f"grep -qx 'GRUB_DEFAULT=0' {path}\n", check)

    def test_grub_is_regenerated_after_an_install_or_a_new_pin(self):
        regen = _named(self.top, "Regenerate the grub configuration")
        self.assertEqual(regen["ansible.builtin.command"]["argv"],
                         ["update-grub"])
        when = " ".join(regen["when"].split())
        self.assertEqual(
            when, "not (rocm_ernic_setup_kernel_current | bool) "
                  "or rocm_ernic_setup_kernel_grub_pinned is changed")


class SlimTasks(unittest.TestCase):

    def setUp(self):
        self.tasks = _tasks(SLIM / "tasks/main.yml")
        self.names = [t["name"] for t in self.tasks]
        self.gated = [
            "List installed kernel packages",
            "Sort the kernel packages into stale and running",
            "Assert the running kernel is installed as a package",
            "Mark the running kernel's packages as manually installed",
            "Check the kernel purge removes kernels and nothing else",
            "Purge kernel packages other than the running one",
            "List what the purged kernels left behind",
            "Remove what the purged kernels left behind",
            "Regenerate the grub configuration without the purged kernels",
            "Check what the kernel purge left"]

    def test_the_steps_run_in_the_order_that_keeps_the_guest_bootable(self):
        order = [self.names.index(n) for n in self.gated]
        self.assertEqual(order, sorted(order))

    def test_every_step_is_off_unless_the_purge_is_asked_for(self):
        for name in self.gated:
            when = _named(self.tasks, name)["when"]
            when = when if isinstance(when, list) else [when]
            self.assertIn("image_slim_purge_old_kernels | bool", when, name)

    def test_the_purge_never_autoremoves(self):
        purge = _named(self.tasks,
                       "Purge kernel packages other than the running one")
        self.assertEqual(purge["ansible.builtin.apt"], {
            "name": "{{ image_slim_stale_kernel_pkgs }}",
            "state": "absent", "purge": True, "autoremove": False})

    def test_only_installed_packages_are_listed(self):
        """dpkg-query -W prints names it knows of; "un" and "rc" are not
        installed, and must not pass for the running kernel's package."""
        cmd = _named(self.tasks, "List installed kernel packages")[
            "ansible.builtin.shell"]["cmd"]
        cmd = cmd.replace(
            "{{ image_slim_kernel_metapackages | join(' ') }}",
            "linux-generic")
        self.assertNotIn("{{", cmd)
        fake = r'''#!/bin/sh
case "$*" in
    *'${db:Status-Abbrev} ${Package}\n'*) ;;
    *) echo "unexpected format: $*" >&2; exit 2 ;;
esac
printf '%s\n' \
    'ii  linux-image-7.0.0-31-generic' \
    'un  linux-image-7.2.6-070206-generic' \
    'rc  linux-modules-7.0.0-12-generic' \
    'iHR linux-headers-7.0.0-31' \
    'ii  linux-image-unsigned-7.2.6-070206-generic' \
    'un  linux-generic'
echo "dpkg-query: no packages found matching linux-modules-extra" >&2
exit 1
'''
        with tempfile.TemporaryDirectory() as tmp:
            tool = Path(tmp) / "dpkg-query"
            tool.write_text(fake)
            tool.chmod(0o755)
            done = subprocess.run(
                ["/bin/bash", "-c", cmd], capture_output=True, text=True,
                env={**os.environ, "PATH": f"{tmp}:{os.environ['PATH']}"})
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertEqual(done.stdout.split(), [
            "linux-image-7.0.0-31-generic",
            "linux-image-unsigned-7.2.6-070206-generic"])

    def test_stale_and_running_are_split_on_the_version_without_flavour(self):
        """Run through Ansible: the _all headers package must be kept."""
        sort = _named(self.tasks,
                      "Sort the kernel packages into stale and running")
        if not shutil.which("ansible-playbook"):
            self.skipTest("needs ansible-playbook to evaluate the filters")
        packages = [
            "linux-headers-7.0.0-31", "linux-headers-7.0.0-31-generic",
            "linux-image-7.0.0-31-generic", "linux-modules-7.0.0-31-generic",
            "linux-headers-7.2.6-070206",
            "linux-headers-7.2.6-070206-generic",
            "linux-image-unsigned-7.2.6-070206-generic",
            "linux-modules-7.2.6-070206-generic",
            "linux-virtual", "linux-image-virtual", "linux-headers-virtual"]
        play = [{"hosts": "localhost", "gather_facts": False, "vars": {
            "ansible_kernel": RUNNING, "image_slim_purge_old_kernels": True,
            "image_slim_kernel_pkgs": {"stdout_lines": packages}},
            "tasks": [
                {k: v for k, v in sort.items()},
                _named(self.tasks,
                       "Assert the running kernel is installed as a package"),
                {"ansible.builtin.debug": {
                    "msg": "stale={{ image_slim_stale_kernel_pkgs | join(',') }}"
                           " running={{ image_slim_running_kernel_pkgs "
                           "| join(',') }}"}}]}]
        with tempfile.TemporaryDirectory() as tmp:
            (Path(tmp) / "play.yml").write_text(yaml.safe_dump(play))
            done = subprocess.run(
                ["ansible-playbook", "-i", "localhost,", "-c", "local",
                 "play.yml"], cwd=tmp, capture_output=True, text=True,
                env={**os.environ, "ANSIBLE_NOCOLOR": "1",
                     "ANSIBLE_STDOUT_CALLBACK": "default"})
        self.assertEqual(done.returncode, 0, done.stdout + done.stderr)
        said = re.search(r'"msg": "stale=(\S*) running=(\S*)"', done.stdout)
        stale, running = (set(g.split(",")) for g in said.groups())
        self.assertEqual(running, {p for p in packages if "7.2.6" in p})
        self.assertEqual(stale, {p for p in packages if "7.2.6" not in p})

    def test_only_paths_the_script_listed_under_three_trees_are_removed(self):
        remove = _named(self.tasks, "Remove what the purged kernels left behind")
        self.assertEqual(remove["ansible.builtin.file"],
                         {"path": "{{ item }}", "state": "absent"})
        self.assertEqual(
            remove["loop"],
            "{{ image_slim_kernel_leftovers.stdout_lines | default([]) }}")
        self.assertEqual(remove["when"], [
            "image_slim_purge_old_kernels | bool",
            "item is match('^/(lib/modules|boot|var/lib/dkms)/[^/]')",
            "'..' not in item",
            "ansible_kernel not in item"])
        for script in (GUARD, LEFTOVERS):
            for word in ("rm ", "rmdir", "unlink", "dpkg -", "--purge",
                         "apt-get purge", "apt-get remove"):
                body = "\n".join(line for line in script.read_text().splitlines()
                                 if not line.lstrip().startswith("#"))
                self.assertNotIn(word, body, f"{script.name}: {word}")

    def test_the_final_check_reads_what_grub_will_boot(self):
        check = _named(self.tasks, "Check what the kernel purge left")
        cmd = check["ansible.builtin.shell"]["cmd"]
        for line in ('test -e "/lib/modules/$running/build"',
                     'test -s "/boot/vmlinuz-$running"',
                     'test -s "/boot/initrd.img-$running"',
                     'test "$(ls -d /lib/modules/*/ | wc -l)" = 1',
                     'test "$(ls /boot/vmlinuz-* | wc -l)" = 1',
                     'test "$loads" = "vmlinuz-$running"'):
            self.assertIn(line, cmd)
        self.assertIn("set -euo pipefail", cmd)

    @unittest.skipUnless(shutil.which("awk"), "needs awk")
    def test_the_awk_that_reads_grub_cfg_sees_every_kernel_it_loads(self):
        check = _named(self.tasks, "Check what the kernel purge left")
        cmd = check["ansible.builtin.shell"]["cmd"]
        program = re.search(r"awk '([^']+)'", cmd).group(1)
        for kernels, want in (([RUNNING], f"vmlinuz-{RUNNING}"),
                              ([RUNNING, OLD],
                               f"vmlinuz-{OLD}\nvmlinuz-{RUNNING}")):
            for options in ({}, {"boot": ""}, {"partuuid": True}):
                with tempfile.TemporaryDirectory() as tmp:
                    cfg = Path(tmp) / "grub.cfg"
                    cfg.write_text(grub_cfg(kernels, **options))
                    out = subprocess.run(
                        f"awk '{program}' {cfg} | sort -u", shell=True,
                        capture_output=True, text=True, check=True).stdout
                self.assertEqual(out.strip(), want, options)


def _fake(directory: Path, name: str, body: str) -> None:
    path = directory / name
    path.write_text("#!/bin/sh\n" + body)
    path.chmod(path.stat().st_mode | stat.S_IXUSR)


@unittest.skipUnless(shutil.which("bash"), "needs bash")
class Guard(unittest.TestCase):
    """kernel-purge-guard.sh against what apt says it would do."""

    STALE = ["linux-image-7.0.0-31-generic", "linux-modules-7.0.0-31-generic",
             "linux-headers-7.0.0-31", "linux-headers-7.0.0-31-generic",
             "linux-virtual", "linux-image-virtual", "linux-headers-virtual"]

    def _run(self, plan: str, stale=None):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            (tmp / "plan").write_text(plan)
            # Says what it was asked, so the test can see it was a dry run.
            _fake(tmp, "apt-get",
                  f'echo "$@" > "{tmp}/asked"\ncat "{tmp}/plan"\n')
            done = subprocess.run(
                ["bash", str(GUARD), "7.2.6-070206",
                 *(self.STALE if stale is None else stale)],
                env={**os.environ, "PATH": f"{tmp}:{os.environ['PATH']}"},
                capture_output=True, text=True)
            asked = (tmp / "asked").read_text() if (tmp / "asked").exists() \
                else ""
        return done.returncode, done.stderr, asked

    def _plan(self, *lines):
        return ("Reading package lists...\nBuilding dependency tree...\n"
                "The following packages will be REMOVED:\n  ...\n"
                + "".join(f"{line}\n" for line in lines))

    def test_a_purge_of_exactly_the_stale_packages_passes(self):
        rc, err, asked = self._run(self._plan(
            *[f"Purg {p} [7.0.0-31.31]" for p in self.STALE]))
        self.assertEqual((rc, err), (0, ""))
        self.assertEqual(asked.split()[:2], ["--simulate", "purge"])
        self.assertEqual(asked.split()[2:], self.STALE)

    def test_another_package_of_a_purged_version_may_go_with_it(self):
        rc, err, _ = self._run(self._plan(
            "Purg linux-image-7.0.0-31-generic [7.0.0-31.31]",
            "Purg linux-modules-extra-7.0.0-31-generic [7.0.0-31.31]",
            "Remv linux-tools-7.0.0-31 [7.0.0-31.31]"))
        self.assertEqual((rc, err), (0, ""))

    def test_a_reverse_dependency_that_is_not_a_kernel_stops_it(self):
        rc, err, _ = self._run(self._plan(
            "Purg linux-headers-virtual [7.0.0.31.31]",
            "Purg amdgpu-dkms [1:7.1.9]"))
        self.assertEqual(rc, 1)
        self.assertIn("would also remove amdgpu-dkms", err)

    def test_anything_of_the_running_kernel_stops_it(self):
        for pkg in ("linux-image-unsigned-7.2.6-070206-generic",
                    "linux-headers-7.2.6-070206",
                    "linux-modules-7.2.6-070206-generic"):
            rc, err, _ = self._run(self._plan(f"Purg {pkg} [7.2.6]"))
            self.assertEqual(rc, 1, pkg)
            self.assertIn("of the running kernel", err)

    def test_the_running_kernel_is_protected_even_when_asked_for(self):
        rc, err, _ = self._run(
            self._plan("Purg linux-image-unsigned-7.2.6-070206-generic [x]"),
            stale=["linux-image-unsigned-7.2.6-070206-generic"])
        self.assertEqual(rc, 1)

    def test_a_purge_that_would_install_something_stops_it(self):
        rc, err, _ = self._run(self._plan(
            "Purg linux-image-7.0.0-31-generic [7.0.0-31.31]",
            "Inst linux-image-7.0.0-33-generic (7.0.0-33.33 Ubuntu:26.04)"))
        self.assertEqual(rc, 1)
        self.assertIn("would INSTALL linux-image-7.0.0-33-generic", err)

    def test_an_apt_that_fails_stops_it(self):
        with tempfile.TemporaryDirectory() as tmp:
            _fake(Path(tmp), "apt-get", "echo 'E: broken' >&2\nexit 100\n")
            done = subprocess.run(
                ["bash", str(GUARD), "7.2.6-070206", *self.STALE],
                env={**os.environ, "PATH": f"{tmp}:{os.environ['PATH']}"},
                capture_output=True, text=True)
        self.assertNotEqual(done.returncode, 0)

    def test_nothing_to_purge_asks_apt_nothing(self):
        rc, err, asked = self._run("", stale=[])
        self.assertEqual((rc, asked), (0, ""))


class Leftovers(unittest.TestCase):
    """kernel-leftovers.sh over a tree built to look like a purged guest."""

    def setUp(self):
        holder = tempfile.TemporaryDirectory()
        self.addCleanup(holder.cleanup)
        self.root = Path(holder.name) / "root"
        self.bin = Path(holder.name) / "bin"
        self.bin.mkdir()
        self.owned: list[str] = []
        for release in (RUNNING, OLD):
            self._make(f"lib/modules/{release}/modules.dep")
            self._make(f"var/lib/dkms/amdgpu/7.1.9/{release}/x86_64/module/a.ko")
            self._link(f"var/lib/dkms/amdgpu/kernel-{release}-x86_64",
                       f"7.1.9/{release}/x86_64")
            for name in ("vmlinuz", "initrd.img", "System.map", "config"):
                self._make(f"boot/{name}-{release}")
        self._make("var/lib/dkms/amdgpu/7.1.9/source/Makefile")
        self._make("var/lib/dkms/amdgpu/7.1.9/build/x.o")
        self._make("boot/grub/grub.cfg")
        self._make(f"boot/initrd.img-{RUNNING}.old-dkms")
        self._make(f"boot/initrd.img-{OLD}.old-dkms")

    def _make(self, rel):
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("x")

    def _link(self, rel, target):
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.symlink_to(target)

    def _list(self, running=RUNNING):
        (self.bin / "owned").write_text("".join(f"{p}\n" for p in self.owned))
        _fake(self.bin, "dpkg-query",
              f'[ "$1" = -S ] && grep -qxF "$2" "{self.bin}/owned"\n')
        done = subprocess.run(
            ["sh", str(LEFTOVERS), running],
            env={**os.environ, "IMAGE_SLIM_ROOT": str(self.root),
                 "PATH": f"{self.bin}:{os.environ['PATH']}"},
            capture_output=True, text=True)
        self.assertEqual(done.returncode, 0, done.stderr)
        return sorted(done.stdout.split())

    def test_everything_of_the_purged_kernel_is_listed_and_nothing_else(self):
        self.assertEqual(self._list(), sorted([
            f"/lib/modules/{OLD}",
            f"/boot/vmlinuz-{OLD}", f"/boot/initrd.img-{OLD}",
            f"/boot/System.map-{OLD}", f"/boot/config-{OLD}",
            f"/boot/initrd.img-{OLD}.old-dkms",
            f"/var/lib/dkms/amdgpu/7.1.9/{OLD}",
            f"/var/lib/dkms/amdgpu/kernel-{OLD}-x86_64"]))

    def test_nothing_of_the_running_kernel_is_ever_listed(self):
        for path in self._list():
            self.assertNotIn(RUNNING, path)
        self.assertNotIn("/boot/grub", " ".join(self._list()))

    def test_every_path_passes_the_tasks_own_filter(self):
        remove = _named(_tasks(SLIM / "tasks/main.yml"),
                        "Remove what the purged kernels left behind")
        pattern = re.search(r"match\('([^']+)'\)", remove["when"][1]).group(1)
        for path in self._list():
            self.assertRegex(path, pattern)
            self.assertNotIn("..", path)

    def test_a_kernel_a_package_still_owns_is_left_whole(self):
        """Another flavour of the kept version, which the purge spares."""
        self.owned = [f"/lib/modules/{OLD}"]
        self.assertEqual(self._list(), [])

    def test_a_boot_file_a_package_owns_is_left(self):
        self.owned = [f"/boot/vmlinuz-{OLD}"]
        self.assertNotIn(f"/boot/vmlinuz-{OLD}", self._list())
        self.assertIn(f"/boot/initrd.img-{OLD}", self._list())

    def test_a_clean_guest_lists_nothing(self):
        for path in self._list():
            target = self.root / path.lstrip("/")
            if target.is_symlink() or target.is_file():
                target.unlink()
            else:
                shutil.rmtree(target)
        self.assertEqual(self._list(), [])
        self.assertTrue((self.root / f"lib/modules/{RUNNING}").is_dir())
        self.assertTrue((self.root / f"boot/vmlinuz-{RUNNING}").is_file())

    def test_an_empty_system_lists_nothing(self):
        shutil.rmtree(self.root)
        self.root.mkdir()
        self.assertEqual(self._list(), [])

